/**
 * Algoritmo Ray-Casting: Verifica si un punto [lng, lat] cae dentro de un polígono
 */
function isPointInPolygon(point, vs) {
  const x = point[0];
  const y = point[1];
  let inside = false;

  for (let i = 0, j = vs.length - 1; i < vs.length; j = i++) {
    const xi = vs[i][0], yi = vs[i][1];
    const xj = vs[j][0], yj = vs[j][1];

    const intersect = ((yi > y) !== (yj > y)) &&
      (x < (xj - xi) * (y - yi) / (yj - yi) + xi);

    if (intersect) inside = !inside;
  }

  return inside;
}

/**
 * Evalúa las coordenadas del cliente contra todas las zonas de Caprichos
 * Prioridad: Z2 -> Z3 -> Z4 -> Z5 -> Z7
 */
function evaluateDeliveryLocation(lat, lng) {
  if (!lat || !lng) {
    return {
      inside: false,
      zona: null,
      costo: 3.0,
      mensaje: "Ubicación no especificada"
    };
  }

  const point = [lng, lat]; // GeoJSON usa [longitud, latitud]

  // Recorremos las zonas en orden
  for (const feature of CAPRICHOS_GEOJSON.features) {
    const coords = feature.geometry.coordinates[0];
    if (isPointInPolygon(point, coords)) {
      const props = feature.properties;
      return {
        inside: true,
        zona: props.zona,
        nombre: props.nombre,
        costo: props.costo,
        color: props.color,
        mensaje: `¡Estás dentro de nuestra zona de cobertura (${props.nombre})!`
      };
    }
  }

  // Si está fuera de los polígonos delimitados
  return {
    inside: false,
    zona: "Fuera de Zona Habitual",
    nombre: "Fuera de Cobertura Directa",
    costo: 5.0, // tarifa estimada de consulta
    color: "#6b7280",
    mensaje: "Tu ubicación está fuera de la zona habitual. Podrás coordinar el envío especial por WhatsApp."
  };
}
