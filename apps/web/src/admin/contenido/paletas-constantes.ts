export function normalizarUrlArchivo(u?: string | null): string | null {
  if (!u) return null;
  if (u.startsWith('/uploads/')) {
    return `/archivos/${u.slice('/uploads/'.length)}`;
  }
  if (u.startsWith('/') || u.startsWith('http://') || u.startsWith('https://') || u.startsWith('data:')) {
    return u;
  }
  return `/archivos/${u}`;
}

